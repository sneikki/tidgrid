package vocab

import "strings"

func (r *Rule) write(b *strings.Builder, depth int) {
	ind := strings.Repeat("  ", depth)
	b.WriteString(ind + r.Key + " {\n")
	for _, n := range r.Nodes {
		if n.Sub != nil {
			n.Sub.write(b, depth+1)
		} else {
			b.WriteString(ind + "  " + n.Prop + ": " + n.Value + ";\n")
		}
	}
	b.WriteString(ind + "}\n")
}

func atomRule(key string, a Atom) *Rule {
	r := &Rule{Key: key}
	for _, kv := range a.Decls {
		r.Nodes = append(r.Nodes, Node{Prop: kv[0], Value: kv[1]})
	}
	return r
}

// Render writes the stylesheet: tokens, elements, keyframes, roles, atoms,
// then the atoms of each breakpoint in file order.
func (v *Vocabulary) Render() string {
	var blocks []*Rule
	if root := v.rootRule(); len(root.Nodes) > 0 {
		blocks = append(blocks, root)
	}
	for _, e := range v.elements {
		blocks = append(blocks, e.Rule)
	}
	blocks = append(blocks, v.keyframeRules()...)
	for _, r := range v.Roles {
		blocks = append(blocks, r.Rule)
	}
	blocks = append(blocks, v.atomRules()...)
	var b strings.Builder
	b.WriteString("/* generated by tidgrid; do not edit */\n")
	for _, r := range blocks {
		b.WriteString("\n")
		r.write(&b, 0)
	}
	return b.String()
}

// rootRule holds every token as a custom property.
func (v *Vocabulary) rootRule() *Rule {
	root := &Rule{Key: ":root"}
	for _, g := range v.Tokens {
		for _, t := range g.Tokens {
			root.Nodes = append(root.Nodes, Node{Prop: "--" + v.Project.Prefix + "-" + g.Name + "-" + t.Name, Value: t.CSS})
		}
	}
	return root
}

func (v *Vocabulary) keyframeRules() []*Rule {
	var out []*Rule
	for _, k := range v.keyframes {
		r := &Rule{Key: "@keyframes " + v.Project.Prefix + "-" + k.Name}
		for _, s := range k.Stops {
			r.Nodes = append(r.Nodes, Node{Sub: s})
		}
		out = append(out, r)
	}
	return out
}

// atomRules writes the plain atoms, one @media block per breakpoint, then the
// hide-below atoms.
func (v *Vocabulary) atomRules() []*Rule {
	var out []*Rule
	for _, a := range v.Atoms {
		if a.Below == "" {
			out = append(out, atomRule("."+esc(a.Class), a))
		}
	}
	for _, bp := range v.Breakpoints {
		m := &Rule{Key: "@media (min-width: " + bp.Value + ")"}
		for _, a := range v.Atoms {
			if a.Below == "" {
				m.Nodes = append(m.Nodes, Node{Sub: atomRule("."+esc(bp.Name+":"+a.Class), a)})
			}
		}
		out = append(out, m)
	}
	for _, a := range v.Atoms { // after every breakpoint block, so they beat md:tg-row
		if a.Below != "" {
			out = append(out, &Rule{Key: "@media (width < " + a.Below + ")", Nodes: []Node{{Sub: atomRule("."+esc(a.Class), a)}}})
		}
	}
	return out
}
